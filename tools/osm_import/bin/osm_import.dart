// One-off: fetch masjids in Mumbai from OpenStreetMap (Overpass API) and write
// an idempotent SQL file. Nothing is written to any database by this script.
//
//   cd tools/osm_import && dart pub get
//   dart run bin/osm_import.dart ../../supabase/osm_mumbai.sql
//
// Then apply the file yourself, local first, then staging, then prod:
//   psql "$DB_URL" -f supabase/osm_mumbai.sql   (pooler URL, port 6543)
//
// Data is © OpenStreetMap contributors, ODbL. Imported rows start `active`
// with no times; re-running updates name/location by osm_id and never
// touches status, so a hidden masjid stays hidden.
import 'dart:convert';
import 'dart:io';

import 'package:http/http.dart' as http;

// Greater Mumbai + Thane + Navi Mumbai (south, west, north, east).
const _bbox = '18.85,72.75,19.35,73.15';

const _query =
    '[out:json][timeout:120];'
    '(nwr["amenity"="place_of_worship"]["religion"="muslim"]($_bbox););'
    'out center tags;';

Future<void> main(List<String> args) async {
  final out = File(args.isEmpty ? 'osm_mumbai.sql' : args.first);
  final res = await http.post(
    Uri.parse('https://overpass-api.de/api/interpreter'),
    headers: {'User-Agent': 'masjid-timer-osm-import/1.0'},
    body: {'data': _query},
  );
  if (res.statusCode != 200) {
    stderr.writeln('Overpass ${res.statusCode}: ${res.body}');
    exit(1);
  }
  final elements = (jsonDecode(res.body)['elements'] as List).cast<Map>();
  final slugs = <String>{};
  final rows = <String>[];
  for (final e in elements) {
    final tags = (e['tags'] as Map?)?.cast<String, String>() ?? const {};
    final lat = (e['lat'] ?? e['center']?['lat']) as num?;
    final lon = (e['lon'] ?? e['center']?['lon']) as num?;
    final name = tags['name:en'] ?? tags['name'];
    if (lat == null || lon == null || name == null || name.trim().length < 2) {
      continue;
    }
    final osmId = '${e['type']}/${e['id']}';
    final ur = tags['name:ur'];
    final ar = tags['name:ar'];
    final local = ur ?? ar;
    final script = ur != null ? "'urdu'" : (ar != null ? "'arab'" : 'null');
    final address = [
      tags['addr:street'],
      tags['addr:suburb'] ?? tags['addr:city'],
    ].whereType<String>().join(', ');
    // ponytail: slugs are unique within one run only; a later run that adds
    // a masjid whose slug an existing row holds fails on the unique index.
    // Re-run with that osm id appended if it ever happens.
    var slug = _slugify(name);
    if (slug.length < 2 || !slugs.add(slug)) {
      slug = '$slug-${e['id']}'.replaceFirst(RegExp('^-'), '');
      slugs.add(slug);
    }
    rows.add(
      "  (${_q(slug)}, ${_q(_cut(name, 120))}, ${local == null ? 'null' : _q(_cut(local, 120))}, "
      "$script, ${address.isEmpty ? 'null' : _q(_cut(address, 300))}, "
      "'SRID=4326;POINT($lon $lat)', 'active', ${_q(osmId)})",
    );
  }
  out.writeAsStringSync('''
-- Generated by tools/osm_import on ${DateTime.now().toUtc().toIso8601String()}.
-- ${rows.length} masjids, © OpenStreetMap contributors (ODbL).
insert into public.masjids (slug, name, name_local, name_script, address, location, status, osm_id)
values
${rows.join(',\n')}
on conflict (osm_id) do update set
  name = excluded.name,
  name_local = excluded.name_local,
  name_script = excluded.name_script,
  address = coalesce(excluded.address, public.masjids.address),
  location = excluded.location;
''');
  stdout.writeln('Wrote ${rows.length} masjids to ${out.path}');
}

String _slugify(String s) => s
    .toLowerCase()
    .replaceAll(RegExp('[^a-z0-9]+'), '-')
    .replaceAll(RegExp(r'^-+|-+$'), '');

String _cut(String s, int max) => s.length <= max ? s : s.substring(0, max);

String _q(String s) => "'${s.replaceAll("'", "''")}'";
